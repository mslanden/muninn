/**
 * Render an inline SVG icon. Returns a string of HTML suitable for
 * `innerHTML` (already escaped) or for use inside a `template literal`.
 *
 * @param {string} name   Key into ICONS. Throws if unknown so missing icons
 *                        fail loud at render time rather than silently rendering nothing.
 * @param {number} [size=14] Pixel size for both width and height.
 * @returns {string}
 */
export function icon(name, size = 14) {
  const body = ICONS[name];
  if (!body) throw new Error(`icon: unknown icon "${name}"`);
  // aria-hidden because surrounding buttons always carry a title/aria-label,
  // and screen readers should read the button's accessible name, not the svg.
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="icon" aria-hidden="true">${body}</svg>`;
}